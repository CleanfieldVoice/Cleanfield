//! Validation of the linear AEC on **measured** room responses.
//!
//! This is the reality check that sits next to `room_conditions.rs`. The
//! synthetic matrix is the designed experiment; this suite replays 18 measured
//! responses from `real/PROVENANCE.md` through the same generator, the same 30 ms
//! static bulk delay, the same near-end and noise scaling and the same
//! production AEC configuration (clock-rate correction on by default).
//!
//! Each response gets four scenes (clean, near end at -6 dB, near end at +3 dB,
//! pink noise at 15 dB) and each scene three seeds: 72 scenes and 216 runs.
//! Thresholds are the contracts the stage has to meet, not values fitted to the
//! table:
//!
//! * stability (no NaN, filter norm under the divergence bound, no divergence
//!   flag and no post-window echo ERLE collapse);
//! * the measured clean set has to cancel echo on average, not just avoid
//!   damage;
//! * near-end speech has to pass through the real rooms essentially untouched;
//! * every double-talk run has to recover inside the measurement window.
//!
//! The numbers behind `ROBUSTNESS.md`'s real-room table are generated by
//! `examples/real_rir_report.rs`, which shares this module.

#[path = "room/mod.rs"]
mod room;

use std::sync::OnceLock;

use room::{mean_min_max, run_scene, RealCondition, RealSceneRuns, FILTER_NORM_LIMIT};

/// Runs the real-room matrix once and shares it across the assertions.
fn matrix() -> &'static [RealSceneRuns] {
    static MATRIX: OnceLock<Vec<RealSceneRuns>> = OnceLock::new();
    MATRIX.get_or_init(room::run_real_matrix)
}

fn values(condition: RealCondition, metric: impl Fn(&room::Metrics) -> f32) -> Vec<f32> {
    matrix()
        .iter()
        .filter(|scene| {
            scene.spec.near_db == condition.near_db() && scene.spec.noise == condition.noise()
        })
        .flat_map(|scene| scene.runs.iter().map(&metric))
        .collect()
}

fn mean(values: &[f32]) -> f32 {
    mean_min_max(values).map_or(f32::NAN, |(mean, _, _)| mean)
}

#[test]
fn every_real_room_run_is_finite_and_bounded() {
    for scene in matrix() {
        for run in &scene.runs {
            assert!(
                !run.has_nan,
                "{}: non-finite residual or filter state",
                scene.spec.name
            );
            assert!(
                run.norm_peak.is_finite() && run.norm_peak <= FILTER_NORM_LIMIT,
                "{}: filter norm peak {} exceeds the divergence bound {FILTER_NORM_LIMIT}",
                scene.spec.name,
                run.norm_peak
            );
            assert!(
                !run.diverged,
                "{}: divergence flag set (echo ERLE pre {} post {})",
                scene.spec.name, run.echo_erle_pre_db, run.echo_erle_post_db
            );
        }
    }
}

#[test]
fn no_real_room_collapses() {
    // "Collapse" is the documented post-window echo ERLE below 3 dB. Every real
    // run has to stay above it, including the 1.05 s room, which is longer than
    // anything the synthetic matrix models.
    for scene in matrix() {
        for run in &scene.runs {
            assert!(
                run.echo_erle_post_db >= 3.0,
                "{}: echo ERLE post {:.1} dB is below the 3 dB collapse bound",
                scene.spec.name,
                run.echo_erle_post_db
            );
        }
    }
}

#[test]
fn clean_real_rooms_cancel_echo_across_the_set() {
    let clean = values(RealCondition::Clean, |metrics| metrics.echo_erle_post_db);
    assert_eq!(clean.len(), room::REAL_RIRS.len() * room::SEEDS.len());
    let (mean, min, max) = mean_min_max(&clean).expect("clean real runs");
    assert!(
        mean >= 12.0,
        "measured-room clean mean echo ERLE {mean:.1} dB is below 12 dB"
    );
    assert!(
        min >= 3.0,
        "measured-room clean minimum echo ERLE {min:.1} dB is below the collapse bound"
    );
    assert!(
        max >= 20.0,
        "no measured room reaches 20 dB clean echo ERLE (best {max:.1} dB)"
    );
}

#[test]
fn near_end_is_preserved_in_real_rooms() {
    for scene in matrix().iter().filter(|scene| scene.spec.near_db.is_some()) {
        for run in &scene.runs {
            let gain = run
                .near_gain_db
                .expect("a real double-talk scene must report a near-end gain");
            assert!(
                (-1.0..=1.0).contains(&gain),
                "{}: near-end gain {gain:+.2} dB is outside +-1 dB",
                scene.spec.name
            );
        }
    }
}

#[test]
fn double_talk_recovers_in_real_rooms() {
    for scene in matrix().iter().filter(|scene| scene.spec.near_db.is_some()) {
        for run in &scene.runs {
            let recovery = run.recovery_ms.unwrap_or_else(|| {
                panic!(
                    "{}: no echo ERLE recovery after double talk (pre {:.1} dB, post {:.1} dB)",
                    scene.spec.name, run.echo_erle_pre_db, run.echo_erle_post_db
                )
            });
            assert!(
                recovery <= 1_500.0,
                "{}: recovery took {recovery:.0} ms",
                scene.spec.name
            );
        }
    }
}

#[test]
fn a_real_room_scene_is_replayable_bit_for_bit() {
    let spec = room::real_scenes()
        .into_iter()
        .find(|spec| spec.real_rir == Some("rvb-largeroom2-far"))
        .expect("the longest measured room");
    assert_eq!(spec.near_db, None);
    let first = run_scene(&spec, 0x00C0_FFEE);
    let second = run_scene(&spec, 0x00C0_FFEE);
    assert_eq!(first.residual.len(), second.residual.len());
    for (index, (&a, &b)) in first
        .residual
        .iter()
        .zip(second.residual.iter())
        .enumerate()
    {
        assert_eq!(
            a.to_bits(),
            b.to_bits(),
            "sample {index} differs between identical real-room runs"
        );
    }
}

#[test]
fn prints_real_room_table() {
    println!(
        "{:<24} {:>8} {:>8} {:>8} {:>8} {:>8}",
        "room", "clean", "DT -6", "DT +3", "pink15", "worst"
    );
    let mut rooms = 0usize;
    for rir in &room::REAL_RIRS {
        let cell = |condition: RealCondition| {
            let values: Vec<f32> = matrix()
                .iter()
                .filter(|scene| {
                    scene.spec.real_rir == Some(rir.id)
                        && scene.spec.near_db == condition.near_db()
                        && scene.spec.noise == condition.noise()
                })
                .flat_map(|scene| scene.runs.iter().map(|metrics| metrics.echo_erle_post_db))
                .collect();
            mean(&values)
        };
        let clean = cell(RealCondition::Clean);
        let minus6 = cell(RealCondition::NearMinus6);
        let plus3 = cell(RealCondition::NearPlus3);
        let pink = cell(RealCondition::Pink15);
        println!(
            "{:<24} {clean:>8.1} {minus6:>8.1} {plus3:>8.1} {pink:>8.1} {:>8.1}",
            rir.id,
            clean.min(minus6).min(plus3).min(pink)
        );
        rooms += 1;
    }
    assert_eq!(rooms, room::REAL_RIRS.len());
    assert_eq!(matrix().len(), rooms * RealCondition::ALL.len());
}

#[test]
fn all_four_conditions_are_measured_on_every_response() {
    assert_eq!(matrix().len(), 72);
    for rir in &room::REAL_RIRS {
        let count = matrix()
            .iter()
            .filter(|scene| scene.spec.real_rir == Some(rir.id))
            .count();
        assert_eq!(count, 4, "{}", rir.id);
    }
}
