//! Scene matrix over the bundled **measured** room responses.
//!
//! This is the bridge between the loader in [`super::real`] and the measurement
//! code in [`super`]. It is deliberately separate from [`super::matrix`]: the
//! synthetic matrix is the designed experiment with 159 seeded runs, while this
//! set is the reality check on it. Adding real rooms to the synthetic matrix
//! would silently change every aggregate in `ROBUSTNESS.md`.
//!
//! Every bundled response gets four scenes, all with the suite's static 30 ms
//! bulk delay:
//!
//! 1. **clean** - speech-like reference through the measured response, no
//!    noise and no near end;
//! 2. **DT -6 dB** - the same, plus near-end speech 6 dB below the echo over
//!    the standard double-talk segment;
//! 3. **DT +3 dB** - the same, with the near end 3 dB above the echo;
//! 4. **pink 15 dB** - the same clean scene plus pink background noise at a
//!    15 dB echo-to-noise ratio.
//!
//! That is 18 x 4 = 72 scenes and 216 seeded runs. The far-end reference, the
//! near-end talker and the noise are generated by the same [`super::signal`]
//! code as the synthetic matrix, and the echo path is the unit-L2-energy
//! measured response from [`super::real::RealRir::impulse`]. No parameter of
//! the generator is special-cased for real rooms, which is what makes the
//! comparison in `ROBUSTNESS.md` meaningful.
//!
//! The production configuration is used: [`super::run_scene`] builds the AEC
//! with [`cf_aec::AecConfig::default`], and clock-rate correction is on by
//! default in that configuration. The scenes have a static path, so the
//! correction stays bypassed, exactly as it does for the synthetic static
//! scenes.

use super::real;
use super::{Metrics, NoiseKind, SceneSpec, SEEDS};

/// The four conditions measured on every real response.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RealCondition {
    /// Reference through the room, no noise, no near end.
    Clean,
    /// Near-end speech at -6 dB relative to the echo.
    NearMinus6,
    /// Near-end speech at +3 dB relative to the echo.
    NearPlus3,
    /// Pink background noise at a 15 dB echo-to-noise ratio.
    Pink15,
}

impl RealCondition {
    /// Stable order used by the report and the tables.
    pub const ALL: [Self; 4] = [Self::Clean, Self::NearMinus6, Self::NearPlus3, Self::Pink15];

    /// Report label.
    pub fn label(self) -> &'static str {
        match self {
            Self::Clean => "clean",
            Self::NearMinus6 => "DT -6 dB",
            Self::NearPlus3 => "DT +3 dB",
            Self::Pink15 => "pink 15 dB",
        }
    }

    /// Noise setting for this condition.
    pub fn noise(self) -> Option<(NoiseKind, f32)> {
        match self {
            Self::Pink15 => Some((NoiseKind::Pink, 15.0)),
            _ => None,
        }
    }

    /// Near-end level for this condition.
    pub fn near_db(self) -> Option<f32> {
        match self {
            Self::Clean | Self::Pink15 => None,
            Self::NearMinus6 => Some(-6.0),
            Self::NearPlus3 => Some(3.0),
        }
    }
}

/// Builds the 72 real-room scenes in a stable order.
///
/// Responses are ordered by measured RT20 (the order of [`real::ALL`]) and each
/// response is followed by its four conditions, so a per-RIR table is a
/// contiguous slice of the result.
pub fn scenes() -> Vec<SceneSpec> {
    let mut out = Vec::with_capacity(real::ALL.len() * RealCondition::ALL.len());
    for rir in &real::ALL {
        for condition in RealCondition::ALL {
            let mut spec =
                SceneSpec::new_real(format!("{} / {}", rir.id, condition.label()), rir.id);
            spec.noise = condition.noise();
            spec.near_db = condition.near_db();
            out.push(spec);
        }
    }
    out
}

/// One real-room scene and the three seeded measurements of it.
pub struct RealSceneRuns {
    pub spec: SceneSpec,
    pub runs: Vec<Metrics>,
}

/// Runs the whole real-room matrix. Each scene is replayed with the three
/// standard seeds, exactly like the synthetic matrix.
pub fn run_matrix() -> Vec<RealSceneRuns> {
    scenes()
        .into_iter()
        .map(|spec| {
            let runs = SEEDS
                .iter()
                .map(|&seed| super::run_scene(&spec, seed).metrics)
                .collect();
            RealSceneRuns { spec, runs }
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_measured_response_gets_all_four_conditions() {
        let scenes = scenes();
        assert_eq!(scenes.len(), real::ALL.len() * RealCondition::ALL.len());
        assert_eq!(scenes.len(), 72);
        for rir in &real::ALL {
            let selected: Vec<&SceneSpec> = scenes
                .iter()
                .filter(|spec| spec.real_rir == Some(rir.id))
                .collect();
            assert_eq!(selected.len(), RealCondition::ALL.len(), "{}", rir.id);
            for condition in RealCondition::ALL {
                let matches: Vec<&&SceneSpec> = selected
                    .iter()
                    .filter(|spec| {
                        spec.near_db == condition.near_db() && spec.noise == condition.noise()
                    })
                    .collect();
                assert_eq!(matches.len(), 1, "{} / {:?}", rir.id, condition);
            }
        }
    }

    #[test]
    fn real_scene_names_are_unique() {
        let mut names: Vec<String> = scenes().into_iter().map(|spec| spec.name).collect();
        names.sort();
        names.dedup();
        assert_eq!(names.len(), 72);
    }

    #[test]
    fn real_scenes_use_a_static_path_and_the_generator_defaults() {
        for spec in scenes() {
            assert_eq!(spec.delay, super::super::DelayKind::Static);
            assert!(spec.real_rir.is_some());
        }
    }
}
