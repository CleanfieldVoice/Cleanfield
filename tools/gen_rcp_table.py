#!/usr/bin/env python3
"""Generate crates/cf-core/src/rcp_table.rs from the captured uint16 table.

The input is a 4096-entry little-endian uint16 .npy.  This script verifies the
file hash, shape and value range, then emits a plain Rust constant.  It is a
build-time tool; the inference path only sees the constant.

Usage:
    python tools/gen_rcp_table.py --npy ../tools/rcpps_table.npy
"""
from __future__ import annotations

import argparse
import hashlib
import struct
import sys
from pathlib import Path

EXPECTED_SHA256 = "2e3bd841cd5cc51da94c416c8806dfd954b9018564acdee35a8eb77091f07683"
EXPECTED_COUNT = 4096


def load_npy_u16(path: Path) -> list[int]:
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != EXPECTED_SHA256:
        raise SystemExit(f"unexpected table sha256: {digest}")
    if data[:6] != b"\x93NUMPY":
        raise SystemExit("not a .npy file")
    major = data[6]
    if major == 1:
        header_len = struct.unpack_from("<H", data, 8)[0]
        data_off = 10 + header_len
    else:
        header_len = struct.unpack_from("<I", data, 8)[0]
        data_off = 12 + header_len
    header = data[10 : 10 + header_len].decode("latin1")
    if "'<u2'" not in header:
        raise SystemExit(f"unexpected dtype in header: {header}")
    if f"({EXPECTED_COUNT},)" not in header:
        raise SystemExit(f"unexpected shape in header: {header}")
    payload = data[data_off:]
    if len(payload) != EXPECTED_COUNT * 2:
        raise SystemExit(f"unexpected payload length {len(payload)}")
    values = list(struct.unpack(f"<{EXPECTED_COUNT}H", payload))
    if min(values) < 4096 or max(values) > 8191:
        raise SystemExit(f"table value out of range: [{min(values)}, {max(values)}]")
    if any(a < b for a, b in zip(values, values[1:])):
        raise SystemExit("table is not monotone non-increasing")
    return values


def emit(values: list[int], out: Path) -> None:
    lines = [
        "// @generated by tools/gen_rcp_table.py - do not edit.",
        "// 4096-entry reciprocal table, pinned by sha256 in the unit tests.",
        "",
        "/// Captured 4096-entry reciprocal significance table.",
        "pub const RCP_TABLE: [u16; 4096] = [",
    ]
    for i in range(0, len(values), 16):
        chunk = ", ".join(str(v) for v in values[i : i + 16])
        lines.append(f"    {chunk},")
    lines.append("];")
    lines.append("")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(
        f"wrote {out} ({len(values)} entries, {out.stat().st_size} bytes, "
        f"sha256 {hashlib.sha256(out.read_bytes()).hexdigest()})"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--npy", type=Path, default=Path(__file__).resolve().parents[2] / "tools" / "rcpps_table.npy")
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[1] / "crates" / "cf-core" / "src" / "rcp_table.rs")
    args = ap.parse_args()
    values = load_npy_u16(args.npy)
    print(f"verified {args.npy}: sha256 ok, 4096 uint16, range [{min(values)}, {max(values)}]")
    emit(values, args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
